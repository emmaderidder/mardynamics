def block_dimension(block: str, m: int, n: int) -> int:
    """Return ``k_j``, the block-coordinate dimension of a canonical block.

    Gives ``k_A = m^2 - 1``, ``k_B = n^2 - 1`` and ``k_gamma = 1``.

    Parameters
    ----------
    block : {"row", "column", "amplitude"}
        Which canonical block.
    m, n : int
        Panel dimensions.

    Returns
    -------
    int
        The block dimension.

    Raises
    ------
    ValueError
        For an unknown block name.
    """
    if block == "row":
        return m * m - 1
    if block == "column":
        return n * n - 1
    if block == "amplitude":
        return 1
    raise ValueError(f"unknown block={block!r}; expected one of {PLANTED_BLOCKS}")


